import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(__dirname, "..")
const cssPath = resolve(pkgRoot, "dist/styles.css")
const outPath = resolve(pkgRoot, "src/styles.generated.ts")

const css = existsSync(cssPath) ? readFileSync(cssPath, "utf8") : ""
const ts = `// AUTO-GENERATED by scripts/build-css-module.mjs. DO NOT EDIT.\nexport default ${JSON.stringify(css)}\n`
writeFileSync(outPath, ts)
console.log(`[loupe] inlined ${css.length} bytes → src/styles.generated.ts`)
